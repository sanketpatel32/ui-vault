// Generates the two registry artifacts the app actually ships:
//   1. src/data/entries.generated.ts — the bundled EntrySummary projection
//      (every UIEntry minus `install`/`sourceUrl`, which only detail pages need).
//   2. public/registry/<source>.json — the full per-source records, fetched on
//      demand by the component detail page.
// Run: npm run registry:gen (also runs inside `npm run llms`, predev/prebuild).
// Output is GENERATED — never hand-edit these files.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fullEntries } from "../src/data/all";
import { sources } from "../src/data/sources";
import type { EntrySummary } from "../src/data/types";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const summaries: EntrySummary[] = fullEntries.map(
  ({ install: _install, sourceUrl: _sourceUrl, ...rest }) => rest,
);

const header = `// GENERATED by scripts/generate-registry.ts — do not edit by hand.
// Bundled search/browse projection; full per-source records live in
// public/registry/<source>.json (fetched on demand by detail pages).
import type { EntrySummary } from "./types";

// Asserted as a whole: checking each of the ~3k literals individually blows
// past TS's union-complexity limit (TS2590).
const data: unknown = [
`;

writeFileSync(
  join(root, "src/data/entries.generated.ts"),
  header +
    summaries.map((e) => `  ${JSON.stringify(e)},`).join("\n") +
    "\n];\n\nexport const entries = data as EntrySummary[];\n",
);
console.log(`wrote src/data/entries.generated.ts (${summaries.length} entries)`);

const registryDir = join(root, "public", "registry");
mkdirSync(registryDir, { recursive: true });
for (const s of sources) {
  const list = fullEntries.filter((e) => e.source === s.id);
  writeFileSync(join(registryDir, `${s.id}.json`), JSON.stringify(list));
}
console.log(`wrote public/registry/{${sources.length} sources}.json`);
